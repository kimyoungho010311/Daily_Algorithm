import sys
sys.stdin = open('input.txt')
'''
민호는 면접봄
면접은 N개의 연속된 질문으로 구성됨
정답을 맞추면 1점이 부여된다.

정답을 연속으로 맞추면 카운터의 숫자가 1씩 증가한다.
만약 틀리면 카운터가 초기화되면서 숫자가 0으로 줄어든다.

카운터가 K가 되면 민호의 점수가 두 배가 된다.
민호의 점수에 먼저 1점이 추가 된 후 총 점수의 두 배가 된다.
면접 시 플레이어의 점수와 연속된 정답을 세는 카운터는 모두 0으로 설정한다.

민호는 정확히 M개의 문제를 맞혔다. 하지만 문제가 나온 순서는 기억하지 못한다.
민호가 받을 수 있는 최소 점수를 출력한다...
'''

T = int(input())
MOD = 1000000009

for tc in range(1, T + 1):
    N, M, K = map(int, input().split())
    # 틀린 문제 개수
    W = N - M

    # 두 배 이벤트 없이 최대한 배치할 수 있는 정답 수 계산
    # 틀린 문제 W개가 각각 K-1개를 막고, 남은 한 자리에 K-1개가 더 올 수 있다.
    safe_limit = W * (K - 1) + (K - 1)

    # 만약 맞힌 개수(M)가 안전 범위 내라면? 점수는 그냥 M점
    if M <= safe_limit:
        print(f"{M % MOD}")
    else:
        # 방패로 못 막고 터져버린 '강제 두 배 묶음'의 개수 X
        # M에서 안전하게 배치 가능한 (W * (K-1))개를 뺸 나머지가
        # K개씩 묶여서 폭탄이 됨
        X = M - W * (K - 1)
        # 이 중 K개씩 묶이는 덩어리 개수
        groups = X // K

        # 등비수열 합 공식 적용: K * (2^(groups+1) - 2)
        # pow(2, groups + 1, MOD)를 사용해 10억 제곱도 빠르게 계산
        doubled_score = (pow(2, groups + 1, MOD) - 2) * K

        # 나머지 점수 (두 배 이벤트 안 받은 낱개들) 계산
        # 전체 정답 M에서 두 배 덩어리에 쓰인 (groups * K)개를 뺸 나머지
        remains = M - (groups * K)

        # 최종 점수 합산 및 모듈러 연산
        ans = (doubled_score + remains) % MOD
        print(f"{ans}")