import sys
sys.stdin = open('input.txt')
"""
줄기세포 도포후 세포 개수
각 세포당 생명력이라는 수치가 있다.

초기에는 비활성 상태이며, 생명력 수치가 x인 줄기 세포의 경우 x시간 동안 비활성이고 이후엔 활성이된다.
활성상태가 되면 x시간 동안 살아있고, 죽는다.
죽는다는건 소멸이 아닌 그냥 가만히 있는거

활성화된 줄기세포는 첫 1시간동안 상, 하, 좌, 우 네 방향 동시에 번식한다.
번식된 줄기 세포는 비활성 상태이다.
이미 해당 자리에 세포가 있으면 그 방향으로 번식은 안한다.
동시에 차지하려고 하면 생명력이 더 큰 세포가 해당 셀을 차지한다.

========================
K를 통해서 배양판의 크기를 추정할 수 있다. -> 이게 뭔소린지 모르겠음 351크기로 하면 일단 되긴한다는데...
만약 2, 2, 10(N, M, K)가 주어질 경우

일단 배양판의 크기는 351 * 351로 설정한다.
각 세포의 시작지점을 올바르게 정하는것도 필요하다.
각 테케별로 배양세포의 시작지점은 배양판의 한 가운데로 정해야겠다.

셀의 점령 우선권은 생명력이 큰 세포들에게 있다.
그러기 위해선 최대값을 가진 세포들부터 움직이게 해야하는데... max()를 통해서 최대값을 찾더라도
만약 x= 3이면 3, 2, 1 순서대로 세포들을 움직여야하기때문에 351 ^ 3 번의 완탐을 통해 세포들을 움직여야한다.
이건 너무 최악의 경우같은데..

각각의 데케마다 최적의 형태로 세포배양판을 구성해야한다.
이게 베스트일거같은데 구현을 못하겠다.

그리고 활성/비활성/죽은상태에 대해서도 로직 작성을 해야한다.
각 시간별로 반복문을 실행할 때

for t in time:
    if t = 세포의x:
        움직이는 로직 작성
        x -= 1

사실 이 방법도 아닌거같다. 처음 반복일때는 작동하겠지만 다음 반복부터는 t와 x가 다신 똑같아질 수 없기 때문에 로직이 작동하지 않는다.
각 셀마다 각 세포를 다뤄야 하기때문에 리스트로 다루기도 힘들거같다.

이건 진짜 못건들겠네..
"""

T = int(input())
for tc in range(1, T+1):
    N, M, K = map(int, input().split())

    # (x, y): [생명력, 경과시간, 상태]
    # 상태S: 0(비활성), 1(활성), 2(죽음)
    cells = {}

    for i in range(N):
        row = list(map(int, input().split()))
        for j in range(M):
            if row[j] > 0:
                # 초기 세포 등록
                cells[(i, j)] = [row[j], 0, 0]

    # K시간동안 진행
    for _ in range(K):
        # 이번 시간에 새로 태어날 후보들 (동시 번식 우선순위 체크용)
        # key: (nx, ny), value: 생명력X
        new_cells = {}

        # 현재 존재하는 모든 세포들 순회
        for (i, j), info in list(cells.items()):
            X, time, status = info

            if status == 2: # 만약 죽은 세포면 넘어가기
                continue

            # 비활성 상태
            if status == 0:
                info[1] += 1 # 시간 1 경과
                if info[1] == X: # 생명력 만큼 시간이 지났다면
                    info[2] = 1 # 활성 상태로 변경
                    info[1] = 0 # 시간 초기화

            # 활성 상태
            if status == 1:
                # 번식 로직: 활성화 직후(time=0)에서만 사방으로 번식
                if info[1] == 0:
                    for di, dj in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                        ni, nj = i + di, j + dj

                        # 이미 세포가 존재하는 곳은 번식 불가
                        if (ni, nj) not in cells:
                            # 동시 번식 시 생명력 높은 놈이 먹기
                            if (ni, nj) not in new_cells or X > new_cells[(ni, nj)]:
                                new_cells[(ni, nj)] = X

                # 나이먹기
                info[1] += 1
                # 생명력 만큼 시간이 지나면 죽음
                if info[1] == X:
                    info[2] = 2 # 죽음 상태로 변경

        # 이번 시간에 번식이 확정된 세포들을 전체 cells에 병합
        for (ni, nj), power in new_cells.items():
            cells[(ni, nj)] = [power, 0, 0]

    # 결과 계산
    ans = 0
    for info in cells.values():
        if info[2] < 2: # 상태가 활성, 비활성인 경우
            ans += 1

    print(f"#{tc} {ans}")